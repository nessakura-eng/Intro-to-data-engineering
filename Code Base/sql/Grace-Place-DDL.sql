-- ============================================================
-- Grace Place Onboarding Passport Database -- table creation (PostgreSQL)
-- Run this file first, then Grace-Place-Data.sql.
-- Every foreign key references exactly one table. Allowed values for
-- the status-style columns are enforced by the application.
-- ============================================================

-- Drop in child-to-parent order so the script can be re-run. CASCADE also removes
-- the security policies from Grace-Place-Supabase-Security.sql, which must be run again afterwards.
DROP TABLE IF EXISTS TaskComment CASCADE;
DROP TABLE IF EXISTS Attachment CASCADE;
DROP TABLE IF EXISTS TaskAssignment CASCADE;
DROP TABLE IF EXISTS MeetAndGreet CASCADE;
DROP TABLE IF EXISTS EmployeeCommittee CASCADE;
DROP TABLE IF EXISTS Committee CASCADE;
DROP TABLE IF EXISTS Task CASCADE;
DROP TABLE IF EXISTS Account CASCADE;
DROP TABLE IF EXISTS Employee CASCADE;
DROP TABLE IF EXISTS Department CASCADE;

CREATE TABLE Department (
    DepartmentID    INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    DepartmentName  VARCHAR(100) NOT NULL,
    GracePlaceTerm  VARCHAR(50)
);

-- Managers and new hires are both rows in Employee. Account.AccountType
-- says which one a person is.
CREATE TABLE Employee (
    EmployeeID              INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    Name                    VARCHAR(100) NOT NULL,
    DepartmentID            INT NOT NULL,
    RoleTitle               VARCHAR(100),
    EmploymentType          VARCHAR(30),
    HireDate                DATE,
    OrientationCompleteDate DATE,
    Email                   VARCHAR(150),
    FOREIGN KEY (DepartmentID) REFERENCES Department(DepartmentID)
);

CREATE TABLE Account (
    AccountID     INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    EmployeeID    INT NOT NULL UNIQUE,
    Username      VARCHAR(100) NOT NULL UNIQUE,
    PasswordHash  VARCHAR(255) NOT NULL,
    AccountType   VARCHAR(20) NOT NULL, -- 'Manager' or 'New Hire'
    FOREIGN KEY (EmployeeID) REFERENCES Employee(EmployeeID)
);

CREATE TABLE Task (
    TaskID          INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    TaskName        VARCHAR(200) NOT NULL,
    Description     TEXT,
    AudienceType    VARCHAR(20) NOT NULL, -- 'New Hire' or 'Management'
    TaskCategory    VARCHAR(20) NOT NULL, -- 'Standardized' / 'Department' / 'RoleSpecific' / 'AdHoc'
    DepartmentID    INT,
    RoleTitle       VARCHAR(100),         -- set when TaskCategory = 'RoleSpecific'
    Checkpoint      VARCHAR(20),          -- 'Pre-Orientation' / 'First Week' / '30-Day' / '60-Day' / '90-Day' / 'Next Steps'
    PerformedBy     VARCHAR(20) NOT NULL, -- 'New Hire' or 'Management'
    SourceDocument  VARCHAR(50),
    FOREIGN KEY (DepartmentID) REFERENCES Department(DepartmentID)
);

CREATE TABLE TaskAssignment (
    AssignmentID          INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    EmployeeID            INT NOT NULL,
    TaskID                INT NOT NULL,
    AssignedByEmployeeID  INT,  -- NULL = auto-assigned standardized task, set = a manager assigned it
    Status                VARCHAR(20) NOT NULL DEFAULT 'Not started',
    DueDate               DATE,
    DateCompleted         DATE,
    FOREIGN KEY (EmployeeID) REFERENCES Employee(EmployeeID),
    FOREIGN KEY (TaskID) REFERENCES Task(TaskID),
    FOREIGN KEY (AssignedByEmployeeID) REFERENCES Employee(EmployeeID)
);

CREATE TABLE Attachment (
    AttachmentID          INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    AssignmentID          INT NOT NULL,
    UploadedByEmployeeID  INT NOT NULL,
    FileName              VARCHAR(255),
    FileURL               VARCHAR(500),
    TextNote              TEXT,
    UploadedAt            TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    FOREIGN KEY (AssignmentID) REFERENCES TaskAssignment(AssignmentID),
    FOREIGN KEY (UploadedByEmployeeID) REFERENCES Employee(EmployeeID)
);

CREATE TABLE TaskComment (
    CommentID         INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    AssignmentID      INT NOT NULL,
    AuthorEmployeeID  INT NOT NULL,
    CommentText       TEXT NOT NULL,
    CreatedAt         TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    FOREIGN KEY (AssignmentID) REFERENCES TaskAssignment(AssignmentID),
    FOREIGN KEY (AuthorEmployeeID) REFERENCES Employee(EmployeeID)
);

CREATE TABLE Committee (
    CommitteeID    INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    CommitteeName  VARCHAR(150) NOT NULL UNIQUE,
    Description    TEXT
);

CREATE TABLE EmployeeCommittee (
    EmployeeID   INT NOT NULL,
    CommitteeID  INT NOT NULL,
    StartDate    DATE,
    EndDate      DATE,
    PRIMARY KEY (EmployeeID, CommitteeID),
    FOREIGN KEY (EmployeeID) REFERENCES Employee(EmployeeID),
    FOREIGN KEY (CommitteeID) REFERENCES Committee(CommitteeID)
);

CREATE TABLE MeetAndGreet (
    MeetAndGreetID  INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    EmployeeID      INT NOT NULL,  -- the new hire
    HostEmployeeID  INT NOT NULL,  -- staff member hosting the session
    ScheduledDate   DATE,
    ScheduledTime   TIME,
    Location        VARCHAR(150),
    Notes           TEXT,
    FOREIGN KEY (EmployeeID) REFERENCES Employee(EmployeeID),
    FOREIGN KEY (HostEmployeeID) REFERENCES Employee(EmployeeID)
);
